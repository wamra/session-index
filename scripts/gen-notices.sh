#!/usr/bin/env bash
# Regenerate THIRD_PARTY_NOTICES.md: every Go module that ends up in a session-index binary for
# the six release targets, with its licence id and the licence text from the module cache.
# Licence ids are detected from the text (a file that combines several licences lists them all).
# A module with no licence file, or text that matches nothing known, is listed as UNKNOWN. Needs a populated module cache (run go build ./... first).
# Usage: scripts/gen-notices.sh [OUTPUT]   (default: THIRD_PARTY_NOTICES.md at the repo root)
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${1:-$ROOT/THIRD_PARTY_NOTICES.md}"
cd "$ROOT"
self="$(go list -m)"

mods="$(for t in darwin/amd64 darwin/arm64 linux/amd64 linux/arm64 windows/amd64 windows/arm64; do
  GOOS="${t%/*}" GOARCH="${t#*/}" CGO_ENABLED=0 go list -deps -f '{{with .Module}}{{.Path}}{{end}}' ./cmd/...
done | sort -u | grep -v -x -F "$self")"

detect() { # file -> licence ids found in the text, joined with " + " (UNKNOWN when none match)
  local f="$1" ids=()
  if grep -q 'Apache License' "$f" && grep -q 'Version 2.0' "$f"; then ids+=(Apache-2.0); fi
  if grep -q 'Redistribution and use in source and binary forms' "$f"; then
    if grep -q 'Neither the name' "$f"; then ids+=(BSD-3-Clause); else ids+=(BSD-2-Clause); fi
  fi
  if grep -q 'Permission is hereby granted, free of charge' "$f"; then ids+=(MIT); fi
  if [ "${#ids[@]}" -eq 0 ]; then echo UNKNOWN; else local IFS=+; echo "${ids[*]}" | sed 's/+/ + /g'; fi
}

tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
: > "$tmp/index"
for m in $mods; do
  info="$(go list -m -f '{{.Version}}|{{if .Replace}}{{.Replace.Path}} {{.Replace.Version}}|{{.Replace.Dir}}{{else}}|{{.Dir}}{{end}}' "$m")"
  ver="${info%%|*}"; rest="${info#*|}"; repl="${rest%%|*}"; dir="${rest#*|}"
  lic="$(ls "$dir" 2>/dev/null | grep -i -E '^(licen[cs]e|copying)' | head -1 || true)"
  notice="$(ls "$dir" 2>/dev/null | grep -i -E '^notice' | head -1 || true)"
  if [ -n "$lic" ]; then
    id="$(detect "$dir/$lic")"; sum="$(shasum -a 256 "$dir/$lic" | cut -d' ' -f1)"
    cat "$dir/$lic" > "$tmp/lic-$sum"
  else id=UNKNOWN; sum=none; fi
  nsum=none
  if [ -n "$notice" ]; then nsum="$(shasum -a 256 "$dir/$notice" | cut -d' ' -f1)"; cat "$dir/$notice" > "$tmp/notice-$nsum"; fi
  printf '%s\t%s\t%s\t%s\t%s\t%s\n' "$m" "$ver" "$id" "$sum" "$nsum" "$repl" >> "$tmp/index"
done

{
  cat <<'HDR'
# Third-party notices

session-index is MIT licensed (see LICENSE). The binaries built from this repository include the
Go modules listed below. This file is generated by `scripts/gen-notices.sh`; do not edit it by hand.
The module list is the union of the dependencies of `./cmd/...` for darwin, linux and windows on
amd64 and arm64. Licence ids are detected from the licence text in the Go module cache; a licence file that combines several licences (klauspost/compress) lists every id found. A module
without a licence file there is listed as UNKNOWN.

## Modules

| Module | Version | Licence |
|---|---|---|
HDR
  while IFS=$'\t' read -r m ver id sum nsum repl; do
    note=""; [ -n "$repl" ] && note=" (built from the fork $repl)"
    printf '| %s | %s%s | %s |\n' "$m" "$ver" "$note" "$id"
  done < "$tmp/index"
  cat <<'MID'

## Components that are not Go modules, or are replaced

- **SQLite** is in the public domain (https://sqlite.org/copyright.html). It is built to WebAssembly and
  embedded in the binary through `github.com/ncruces/go-sqlite3`. SQLite needs no licence notice.
- **github.com/ncruces/go-sqlite3** (MIT, Copyright Nuno Cruces) is the pure-Go SQLite driver. This
  repository replaces it, through a `replace` directive in `go.mod`, with the public fork
  `github.com/wamra/go-sqlite3`, which is the same code plus three Windows WAL fixes. The fork carries
  the original MIT licence, reproduced below.
- **sqlite-vec** (https://github.com/asg017/sqlite-vec, Copyright Alex Garcia) is compiled to
  WebAssembly and embedded through `github.com/asg017/sqlite-vec-go-bindings` v0.1.6. sqlite-vec is
  dual licensed under MIT and Apache-2.0, as its upstream repository states. The bindings module ships
  no licence file in the Go module cache, so it is listed as UNKNOWN in the table above; the sqlite-vec
  licence texts below were copied from the upstream repository (`LICENSE-MIT`, `LICENSE-APACHE`).
- **klauspost/compress** has one licence file that combines BSD-3-Clause, Apache-2.0 and MIT parts (all reproduced below), **wazero** (Apache-2.0), **golang.org/x/crypto, x/sys, x/term**
  (BSD-3-Clause) and the **AWS SDK for Go v2** (Apache-2.0) are Go modules covered by the table above.

## Licence texts
MID
  for f in "$ROOT"/scripts/notices/sqlite-vec.LICENSE-MIT "$ROOT"/scripts/notices/sqlite-vec.LICENSE-APACHE; do
    case "$f" in *MIT) t="sqlite-vec (MIT option), upstream asg017/sqlite-vec" ;; *) t="sqlite-vec (Apache-2.0 option), upstream asg017/sqlite-vec" ;; esac
    printf '\n### %s\n\n````text\n' "$t"; cat "$f"; printf '````\n'
  done
  for sum in $(cut -f4 "$tmp/index" | grep -v '^none$' | sort -u); do
    id="$(awk -F'\t' -v s="$sum" '$4==s{print $3; exit}' "$tmp/index")"
    list="$(awk -F'\t' -v s="$sum" '$4==s{print $1}' "$tmp/index" | paste -sd, - | sed 's/,/, /g')"
    printf '\n### %s: %s\n\n````text\n' "$id" "$list"; cat "$tmp/lic-$sum"; printf '````\n'
  done
  for nsum in $(cut -f5 "$tmp/index" | grep -v '^none$' | sort -u); do
    list="$(awk -F'\t' -v s="$nsum" '$5==s{print $1}' "$tmp/index" | paste -sd, - | sed 's/,/, /g')"
    printf '\n### NOTICE: %s\n\n````text\n' "$list"; cat "$tmp/notice-$nsum"; printf '````\n'
  done
  unk="$(awk -F'\t' '$3=="UNKNOWN"{print $1}' "$tmp/index" | paste -sd, - | sed 's/,/, /g')"
  [ -z "$unk" ] || printf '\n## Unresolved\n\nNo licence file was found in the module cache for: %s.\n' "$unk"
} > "$OUT"
echo "gen-notices: wrote $OUT"
